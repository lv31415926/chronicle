import fs from "fs";
import { MAX_TITLE, MAX_SUMMARY } from "./limits.mjs";
global.window = {};
const [f, key] = process.argv.slice(2);
const src = fs.readFileSync(f, "utf8");
new Function("window", src)(global.window);
const arr = global.window.__CHRONICLE_CHUNK[key];
const DIMS = ["politics","figure","science","culture","art","military","economy","institution","explore","disaster"];
let err = [];
const seen = new Set(), dimC = {}, wC = {};
arr.forEach((e) => {
  if (seen.has(e.id)) err.push("dup id " + e.id); seen.add(e.id);
  if (!Number.isInteger(e.year) || e.year === 0) err.push("bad year " + e.id);
  const m = new RegExp("^cn--" + e.year + "--.").exec(e.id);
  if (!m) err.push("id/year mismatch " + e.id);
  if (!e.id.startsWith("cn--")) err.push("bad track prefix " + e.id);
  if (!DIMS.includes(e.dim)) err.push("bad dim " + e.id + " " + e.dim);
  if (typeof e.weight !== "number" || !Number.isInteger(e.weight) || e.weight < 1 || e.weight > 5) err.push("bad weight " + e.id);
  if ([...e.title].length > MAX_TITLE) err.push(`title>${MAX_TITLE} ` + e.id);
  if (!e.summary || [...e.summary].length > MAX_SUMMARY) err.push(`summary>${MAX_SUMMARY} ` + e.id);
  const d = e.detail || {};
  ["background","process","impact","figures","place","state","sources","tags"].forEach(k => { if (!d[k] || (Array.isArray(d[k]) && !d[k].length)) err.push("detail missing " + k + " " + e.id); });
  if (!d.sources || !d.sources.length) err.push("no sources " + e.id);
  if (!d.tags || d.tags.length < 2) err.push("tags<2 " + e.id);
  if (!d.figures || d.figures.length < 1) err.push("figures empty " + e.id);
  if ((e.related || []).length > 4) err.push("related>4 " + e.id);
  (e.related || []).forEach(r => { if (!r.startsWith("cn--") && !r.startsWith("world--")) err.push("bad related " + e.id + " " + r); });
  dimC[e.dim] = (dimC[e.dim] || 0) + 1; wC[e.weight] = (wC[e.weight] || 0) + 1;
});
const n = arr.length;
const p = x => (100 * x / n).toFixed(1) + "%";
console.log(key, "count", n, "errs", err.length);
console.log("w1..5", [1,2,3,4,5].map(w => wC[w] || 0).join("/"), "w5", p(wC[5]||0), "w4+", p((wC[4]||0)+(wC[5]||0)));
console.log("dims", DIMS.map(d => d[0] + ":" + (dimC[d] || 0)).join(" "));
console.log("yrange", arr[0] && arr[0].year, arr[n-1] && arr[n-1].year);
err.slice(0, 25).forEach(x => console.log(" -", x));
